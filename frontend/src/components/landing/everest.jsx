/**
 * EVEREST — a cinematic technical illustration, constructed.
 *
 * NOT a photograph, not a logo, not a triangle. This is the Khumbu skyline as a
 * matte painting assembled from geometric facets: the summit pyramid, the
 * Southeast Ridge stepping down to the South Col, Lhotse across the saddle, and
 * the Nuptse wall closing the foreground.
 *
 * WHY THE GEOMETRY IS GENERATED, NOT TYPED
 *
 * A mountain drawn as ~200 hand-written polygon strings is unreadable and
 * untunable — moving the summit 40px left means editing every coordinate. So
 * the massif is built from RIDGES: polylines generated by two functions with a
 * handful of shape parameters. Faces are the quads BETWEEN consecutive ridges.
 * That gives the real structure of a big face — buttresses and the gullies
 * between them — and the whole mountain re-proportions from a few numbers.
 *
 * PROPORTION IS THE WHOLE GAME
 *
 * Everest from the south is a BROAD wedge, not a spike. Its West Ridge runs out
 * at barely 30 degrees and takes most of a horizon to come down. The first
 * build of this file used a steep falloff and produced a needle — correct in
 * its parts, wrong at a glance, and wrong at a glance is just wrong. The ridge
 * exponents below are the fix, and they are the most load-bearing numbers here.
 *
 * THE TEN-VALUE RULE
 *
 * Every facet indexes into `--tr0..--tr9`. There are ten values in this
 * painting, not two hundred. That constraint is what keeps a heavily faceted
 * illustration from turning to gravel: shapes group into readable planes
 * because they share exact values, the way a screen print does.
 *
 * Because those ten values are CSS custom properties, a theme switch re-skins
 * the entire mountain with NO React render — the attribute flips on <html> and
 * every polygon follows. Dark mode is a different hour, not an inversion.
 *
 * EVERYTHING IS CLIPPED TO ITS OWN SILHOUETTE. Facets are generated, so they
 * overshoot the outline by design; the clip is what lets the generators stay
 * simple instead of every ridge having to solve for where it meets the skyline.
 *
 * LIGHT COMES FROM THE UPPER LEFT, always.
 */

export const VIEW = { w: 1600, h: 900 }

const round = (n) => Math.round(n * 10) / 10
const pts = (list) => list.map(([x, y]) => `${round(x)},${round(y)}`).join(' ')

/**
 * Terrain ramp lookup: 0 (deepest shadow) -> 1 (brightest snow).
 *
 * Deliberately QUANTISED to the ten ramp steps rather than interpolated. Two
 * facets given 0.61 and 0.64 resolve to the same value and merge into one
 * plane, which is exactly the grouping that makes a face readable.
 */
export const tr = (v) => `var(--tr${Math.max(0, Math.min(9, Math.round(v * 9)))})`

/* ----------------------------------------------------------------- ridges */

const STEPS = 10

/**
 * Deterministic value noise in -1..1.
 *
 * `Math.random()` is unusable here: the mountain would reshuffle on every
 * render and differ between the first paint and every one after. A hash of the
 * index is stable forever and still looks arbitrary, which is the only property
 * that matters.
 */
const noise = (n) => {
  const s = Math.sin(n * 127.1) * 43758.5453
  return (s - Math.floor(s)) * 2 - 1
}

/**
 * A FACE ridge: falls from the summit region to the bottom of the frame.
 *
 * The exponents are the shape language. y grows slightly faster than linear so
 * detail concentrates near the summit; x grows a little slower than linear so
 * the profile is gently concave — near-vertical up high, flaring into the base.
 * At 1.28 (the first attempt) this produced a needle; 1.06 produces a mountain.
 *
 * JITTER IS THE DIFFERENCE BETWEEN ROCK AND A TENT.
 *
 * With smooth ridges, every facet between two of them is a long clean triangle
 * converging on the apex, and a fan of clean triangles is read by the eye as
 * PLEATS — a circus tent, a folded paper fan, anything but a mountain. No
 * amount of shading fixes it, because the problem is the edges.
 *
 * Real ridges zigzag. Displacing each interior point by a stable hash turns
 * every facet into an irregular quad, and the face immediately reads as broken
 * rock. The displacement tapers to zero at both ends (the `sin` envelope) so
 * ridges still meet the summit and the base exactly where they are told to.
 */
function faceRidge(top, bottomX, bow = 0, seed = 1) {
  const out = []
  for (let i = 0; i < STEPS; i += 1) {
    const t = i / (STEPS - 1)
    const envelope = Math.sin(t * Math.PI)
    out.push([
      top[0] +
        (bottomX - top[0]) * t ** 1.06 +
        Math.sin(t * Math.PI) * bow +
        noise(seed * 31.7 + i * 17.3) * 34 * envelope,
      top[1] + (VIEW.h - top[1]) * t ** 0.94 + noise(seed * 57.1 + i * 13.9) * 26 * envelope,
    ])
  }
  return out
}

/** The quad strip between two ridges, from step `from` to step `to`. */
function band(a, b, from, to) {
  return [...a.slice(from, to + 1), ...b.slice(from, to + 1).reverse()]
}

