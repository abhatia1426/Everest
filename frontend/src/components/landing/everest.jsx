/**
 * THE SKYLINE, as a normalised series.
 *
 * The West Ridge and the Southeast Ridge, sampled left-to-right and rescaled
 * into 0..1 on both axes. Downstream sections plot it as a price line.
 *
 * This is the single most important export in the file. When section 03 draws
 * "the market" and the curve is Everest's actual profile, the transition from
 * mountain to data is not a metaphor the copy has to assert — the reader
 * recognises the shape, and the page earns the claim silently. A chart of
 * invented numbers next to a mountain would just be two pictures.
 */
export const SKYLINE = (() => {
  const raw = [...WEST_RIDGE].reverse().concat(SE_RIDGE.slice(1))
  const xs = raw.map((p) => p[0])
  const ys = raw.map((p) => p[1])
  const x0 = Math.min(...xs)
  const x1 = Math.max(...xs)
  const y0 = Math.min(...ys)
  const y1 = Math.max(...ys)
  return raw.map(([x, y]) => [(x - x0) / (x1 - x0), 1 - (y - y0) / (y1 - y0)])
})()

/**
 * CONTOURS OF THIS PEAK.
 *
 * Successive insets of the real massif silhouette, contracted toward the
 * summit — so the rings are the topographic map of the mountain the reader has
 * just been looking at, not a generic set of arcs. The eye recognises the
 * outline even when it cannot say why, which is what makes the mountain ->
 * terrain transition land.
 *
 * @param {number} count  number of rings
 * @param {number} at     0..1 — how far the rings have "grown in"
 */
/**
 * The point strings for `count` nested contour rings, outermost first.
 *
 * Exposed separately so a caller can animate rings INDIVIDUALLY — section 02
 * draws the map outward from the summit, one ring at a time, which needs a
 * MotionValue per ring rather than one opacity on the group.
 */
export function contourRings(count = 9) {
  const focus = APEX
  const skyline = [...WEST_RIDGE].reverse().concat(SE_RIDGE.slice(1))

  return Array.from({ length: count }).map((_, i) => {
    /* Rings start already well inside the silhouette. Beginning near k=0 made
       the outermost ring almost the full skyline — a 1,500px arc sweeping out
       of the frame across the foreground, which read as a stray swoosh rather
       than as a contour of the peak. Contours belong ON the mountain. */
    const k = 0.26 + (i / Math.max(1, count - 1)) * 0.66
    return pts(
      skyline.map(([x, y]) => [
        focus[0] + (x - focus[0]) * (1 - k * 0.86),
        focus[1] + (y - focus[1]) * (1 - k * 0.86),
      ]),
    )
  })
}

export function MassifContours({ count = 9, stroke = 'var(--border-strong)', className = '' }) {
  const focus = APEX

  /*
   * THE SKYLINE ONLY — not the closed silhouette.
   *
   * Contracting the full outline included its base: the two frame edges and the
   * straight run along y=900. Scaled down, those became long straight diagonals
   * cutting across the composition, which read as stray rules rather than as
   * contours and made the background look like a mistake.
   *
   * A contour line around a peak is an OPEN arc. Using just the West and
   * Southeast ridges gives exactly that, and nesting them produces the familiar
   * stacked-arc topographic map of this specific mountain.
   */
  const skyline = [...WEST_RIDGE].reverse().concat(SE_RIDGE.slice(1))

  return (
    <g className={className} fill="none" stroke={stroke}>
      {Array.from({ length: count }).map((_, i) => {
        /* Rings start already well inside the silhouette. Beginning near k=0 made
       the outermost ring almost the full skyline — a 1,500px arc sweeping out
       of the frame across the foreground, which read as a stray swoosh rather
       than as a contour of the peak. Contours belong ON the mountain. */
    const k = 0.26 + (i / Math.max(1, count - 1)) * 0.66
        const ring = skyline.map(([x, y]) => [
          focus[0] + (x - focus[0]) * (1 - k * 0.86),
          focus[1] + (y - focus[1]) * (1 - k * 0.86),
        ])
        return (
          <polyline
            key={i}
            points={pts(ring)}
            strokeWidth={i === 0 ? 1.4 : 1}
            opacity={1 - i * 0.07}
          />
        )
      })}
    </g>
  )
}

