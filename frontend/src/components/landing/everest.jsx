/**
 * The Nuptse wall.
 *
 * Its signature is FLUTINGS — near-vertical ribs of snow and ice hanging off
 * the crest, carved by spindrift. Drawn as narrow tapering strips, they give
 * the eye vertical structure and scale across 1,700px of otherwise flat dark
 * shape. Drawn as wide triangles (the first attempt) they read as teeth, which
 * is why they are narrow and shallow here.
 */
export function Nuptse({ id }) {
  /*
   * THE WALL IS FACETED, NOT FLAT.
   *
   * Earlier passes drew a flat near-black polygon with thin flutings hanging
   * off the crest, and it read as a fringed curtain across the bottom quarter
   * of the screen — 250px of dead ink with a decorative edge. A quarter of the
   * hero cannot be a void.
   *
   * So the wall is built the same way the massif is: a plane between each pair
   * of crest points, dropping to the frame edge, each one a slightly different
   * value. Alternating faces read as the buttresses of a wall seen end-on, and
   * the whole foreground gains structure while staying dark enough to sit in
   * front of everything else.
   */
  /*
   * THE WALL IS A TILED SURFACE, NOT A ROW OF SHAPES.
   *
   * Two builds failed here for the same reason. Each crest segment was given
   * its own independent quad, so adjacent faces did not share vertices — they
   * overlapped and gapped, every face kept its own hard left and right edge,
   * and the result read as a stockade of columns (full height) and then as a
   * row of concrete blocks (cropped). Both times the wall looked like objects
   * standing in front of the mountain rather than a surface belonging to it.
   *
   * The fix is a shared BASE line: one vertex per crest vertex, offset down and
   * damped toward a mean. Face `i` spans crest[i]-crest[i+1]-base[i+1]-base[i],
   * so consecutive faces share an entire edge exactly. The surface is now
   * continuous by construction — the facets are seams in one plane instead of
   * boundaries between separate ones — and values only ever differ by a step or
   * two, so the eye reads modulation rather than a pattern.
   */
  /*
   * A SHALLOW crest band, and nothing else below it.
   *
   * The detail budget of this illustration belongs to Everest. Every attempt to
   * model the foreground wall in depth — full-height faces, cropped faces,
   * tiled faces — produced something that competed with the summit and lost:
   * the eye kept going to a row of grey slabs at the bottom of the frame
   * instead of to the mountain, in both themes but glaringly in daylight.
   *
   * A cinematic foreground is a SILHOUETTE. So the wall is one dark mass and
   * the only modelling is a shallow band where the light actually lands, along
   * the crest. The band still tiles (shared vertices, no seams), but at ~70px
   * against a 280px wall it reads as a lit edge on a dark shape — which is
   * exactly what it is — instead of as a row of objects.
   */
  const BASE = NUPTSE_CREST.map(([x, y], i) => [
    x + noise(i * 9.3) * 16,
    y + 58 + noise(i * 4.7) * 24,
  ])

  const faces = NUPTSE_CREST.slice(0, -1).map(([x, y], i) => (
    <polygon
      key={`nf-${i}`}
      points={pts([[x, y], NUPTSE_CREST[i + 1], BASE[i + 1], BASE[i]])}
      fill={tr(i % 2 ? 0.28 : 0.2)}
    />
  ))

  return (
    <g>
      <clipPath id={`${id}-nuptse`}>
        <polygon points={pts(NUPTSE_OUTLINE)} />
      </clipPath>

      <polygon points={pts(NUPTSE_OUTLINE)} fill={tr(0.08)} />

      <g clipPath={`url(#${id}-nuptse)`}>
        {faces}

        {/* The lit crest line — thin, and what stops a near-black mass reading
            as a hole punched in the page. */}
        <polyline
          points={pts(NUPTSE_CREST)}
          fill="none"
          stroke={tr(0.6)}
          strokeWidth="2.2"
          strokeLinejoin="round"
          opacity="0.7"
        />
      </g>
    </g>
  )
}

