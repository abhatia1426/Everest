/**
 * The massif.
 *
 * Painted back to front in one pass: silhouette, then the face broken into
 * three altitude zones per rib (snow / terrace / lower rock), then couloir and
 * crevasse detail, then the summit cap last so it sits on top of everything.
 */
export function EverestMassif({ id }) {
  return (
    <g>
      <clipPath id={`${id}-massif`}>
        <polygon points={pts(MASSIF_OUTLINE)} />
      </clipPath>

      {/* The silhouette. Everything after this is clipped into it, so a facet
          that overshoots shows the massif colour and never the sky. */}
      <polygon points={pts(MASSIF_OUTLINE)} fill={tr(0.22)} />

      <g clipPath={`url(#${id}-massif)`}>
        {/* ------------------------------------------------ the face, in zones */}
        {RIDGES.slice(0, -1).map((left, i) => {
          const right = RIDGES[i + 1]
          const lit = FACE_LIT[Math.min(i, FACE_LIT.length - 1)]
          const snowTo = SNOW_TO[Math.min(i, SNOW_TO.length - 1)]
          const midTo = MID_TO[Math.min(i, MID_TO.length - 1)]

          return (
            <g key={`face-${i}`}>
              {/* Lower rock — furthest from the light and closest to the haze
                  pooling at the base, so the darkest zone on the face. */}
              <polygon points={pts(band(left, right, midTo, STEPS - 1))} fill={tr(lit * 0.6)} />
              {/* The mid-face terrace. */}
              <polygon points={pts(band(left, right, snowTo, midTo))} fill={tr(lit)} />
              {/*
                Snow held on the upper rib.

                +0.26 and confined to one or two steps. At +0.32 across three
                steps these became enormous pale triangles fanning half the
                height of the mountain, and the face read as overlapping sheets
                of frosted glass rather than as rock — the ribs stopped being
                structure and became transparency. A big face is mostly DARK
                rock; snow is the exception on it, and the summit cap below is
                the only place the ramp is allowed to reach the top.
              */}
              <polygon
                points={pts(band(left, right, 0, snowTo))}
                fill={tr(Math.min(0.82, lit + 0.26))}
              />
            </g>
          )
        })}

        {/*
          The flank falling east toward the South Col. Turned fully away from
          the light, so it goes nearly black — and that is precisely what makes
          the South Col read as a gap rather than as a drawn line.
        */}
        {/* 0.13 made this a black void beside the summit — a shark fin cut out
            of the sky rather than a face turned away from the light. 0.19 still
            reads as the shadow side and still opens the col. */}
        <polygon
          points={pts([...EAST_BOUND, [1310, VIEW.h], ...SE_RIDGE.slice(7).reverse()])}
          fill={tr(0.19)}
        />

        {/*
          COULOIRS — snow-choked gullies on the shadowed ribs.

          Confined to the upper half of the face and to the ribs that are
          otherwise dark. Real faces work exactly this way: snow survives in the
          gullies the sun and wind cannot reach, so the darkest parts of a face
          carry the brightest lines. The detail that rewards actually looking.
        */}
        {[2, 4, 6].map((i) => {
          const left = RIDGES[i]
          const right = RIDGES[i + 1]
          const mix = (t) =>
            left.map(([lx, ly], k) => [lx + (right[k][0] - lx) * t, ly + (right[k][1] - ly) * t])
          /*
             Kept SHORT and quiet. Run to step 4 at 0.42 opacity they became two
             pale streaks raking the whole face — read as light rays crossing
             the mountain rather than as snow lying in it, which is a worse
             artefact than the detail was worth.
          */
          return (
            <polygon
              key={`couloir-${i}`}
              points={pts(band(mix(0.38), mix(0.5), 1, 5))}
              fill={tr(FACE_LIT[i - 1] + 0.3)}
              opacity="0.28"
            />
          )
        })}

        {/*
          STRATA — the horizontal half of the face.

          Everest's south side is layered sedimentary rock, and two of its bands
          are famous enough to be route landmarks: the YELLOW BAND of limestone
          around 7,600m, and the darker step of the Geneva Spur beneath it.

          They are here for a compositional reason as much as a geological one.
          The ribs above are all radial, and radial lines alone converge on the
          apex and read as pleats in a tent. Crossing them with horizontal
          strata turns the face into a GRID of facets — and a grid reads as
          rock, gives the eye a sense of scale, and destroys the cone.

          Tilted slightly, because bedding planes are never level, and drawn at
          low opacity so they modulate the ribs rather than replacing them.
        */}
        {[
          { a: [-70, 372], b: [1200, 300], h: 46, v: 0.82, o: 0.16 },
          { a: [-70, 470], b: [1240, 384], h: 30, v: 0.1, o: 0.2 },
          { a: [-70, 556], b: [1280, 470], h: 58, v: 0.62, o: 0.11 },
          { a: [-70, 690], b: [1300, 604], h: 40, v: 0.06, o: 0.22 },
        ].map((s, i) => (
          <polygon
            key={`strata-${i}`}
            points={pts([s.a, s.b, [s.b[0], s.b[1] + s.h], [s.a[0], s.a[1] + s.h]])}
            fill={tr(s.v)}
            opacity={s.o}
          />
        ))}

        {/* The bergschrund, where the upper snowfields break from the face. */}
        <path
          d="M812 452 C 900 398, 1010 376, 1112 414"
          stroke={tr(0.84)}
          strokeWidth="2"
          fill="none"
          opacity="0.34"
        />

        {/* Crevasse hairlines. At this distance a crevasse is a value break,
            never a drawn shape. */}
        <g stroke={tr(0.3)} strokeWidth="1.6" fill="none" opacity="0.5">
          <path d="M946 316 C 984 328, 1026 326, 1062 314" />
          <path d="M904 372 C 962 390, 1030 386, 1084 368" />
          <path d="M1108 336 C 1136 352, 1158 366, 1182 376" />
        </g>
      </g>

      {/*
        THE SUMMIT SNOW CAP.

        Everest's summit is not a point of rock — it is a small, slightly domed
        snowfield, the last thing on the mountain to hold light. The brightest
        value on the page, and the only place tr9 appears at full strength.
      */}
      <polygon
        points={pts([
          [960, 288],
          [978, 252],
          [994, 228],
          APEX,
          [1030, 238],
          [1048, 264],
          [1064, 280],
          [1042, 300],
          [1004, 306],
          [974, 302],
        ])}
        fill={tr(0.99)}
      />
      {/* The cap's own shadow side, so it reads as a dome and not a decal. */}
      <polygon
        points={pts([APEX, [1030, 238], [1048, 264], [1064, 280], [1042, 300], [1010, 286]])}
        fill={tr(0.76)}
      />

      {/*
        THE SUMMIT RIDGE, lit.

        One hairline of the brightest value along the skyline from the apex to
        the South Summit. Real summit ridges catch light on the windward cornice
        and separate from the sky by a hard edge; without it the top of the
        pyramid dissolves into the atmosphere and the peak loses its point.
      */}
      <polyline
        points={pts(SE_RIDGE.slice(0, 5))}
        fill="none"
        stroke={tr(1)}
        strokeWidth="2.4"
        strokeLinecap="round"
        opacity="0.92"
      />
      <polyline
        points={pts(WEST_RIDGE.slice(0, 4))}
        fill="none"
        stroke={tr(0.95)}
        strokeWidth="2"
        strokeLinecap="round"
        opacity="0.5"
      />
    </g>
  )
}

